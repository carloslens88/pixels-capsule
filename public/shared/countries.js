export const COUNTRY_CODES = Object.keys(COUNTRIES);

export function flagEmoji(code) {
  return [...code].map((c) => String.fromCodePoint(127397 + c.charCodeAt(0))).join("");
}

export function countryName(code, lang) {
  const entry = COUNTRIES[code];
  if (!entry) return code;
  return lang === "en" ? entry[1] : entry[0];
}

export function sortedCountryCodes(lang) {
  return [...COUNTRY_CODES].sort((a, b) => countryName(a, lang).localeCompare(countryName(b, lang), lang));
}
